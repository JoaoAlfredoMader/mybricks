import { betterAuth } from "better-auth";
import { createAuthMiddleware, getSessionFromCtx } from "better-auth/api";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { admin, anonymous, openAPI, organization } from "better-auth/plugins";
import type { Env } from "../../config/env.js";
import type { Mailer } from "../../lib/mail/mailer.js";
import type { Database } from "../../db/database.js";
import * as schema from "../../db/schema.js";
import { type AuditEvent, type AuditRecorder, clientIp } from "../audit/audit.recorder.js";
import { verificationEmail } from "./auth-emails.js";
import type { ProvisioningService } from "./provisioning.service.js";

/** How long the confirmation link works. */
const VERIFICATION_TTL_SECONDS = 24 * 60 * 60;

export interface AuthDependencies {
  db: Database;
  env: Env;
  provisioning: ProvisioningService;
  audit: AuditRecorder;
  mailer: Mailer;
  /** Keeps work alive after the response (`ctx.waitUntil` on a Worker). Omitted on a server, where it just runs. */
  runInBackground?: (promise: Promise<unknown>) => void;
}

interface SessionUser {
  id: string;
  name: string;
  email: string;
}

export function createAuth({ db, env, provisioning, audit, mailer, runInBackground }: AuthDependencies) {
  const googleEnabled = Boolean(env.GOOGLE_CLIENT_ID && env.GOOGLE_CLIENT_SECRET);

  /** Leaves a trace of an authentication event, with the request's address and browser. */
  async function trace(
    request: Request | undefined,
    event: Omit<AuditEvent, "ipAddress" | "userAgent" | "actor"> & { user: SessionUser | null },
  ) {
    const { user, ...rest } = event;
    const role = user && event.organizationId ? await provisioning.memberRole(event.organizationId, user.id) : null;
    await audit.record({
      ...rest,
      actor: user ? { ...user, role } : null,
      ipAddress: request ? clientIp(request.headers) : null,
      userAgent: request?.headers.get("user-agent") ?? null,
    });
  }

  return betterAuth({
    appName: "MyBricks",
    baseURL: env.BETTER_AUTH_URL,
    secret: env.BETTER_AUTH_SECRET,
    trustedOrigins: [env.FRONTEND_URL],

    database: drizzleAdapter(db, {
      provider: "sqlite",
      schema: {
        user: schema.users,
        session: schema.sessions,
        account: schema.accounts,
        verification: schema.verifications,
        organization: schema.organizations,
        member: schema.members,
        invitation: schema.invitations,
      },
    }),
    // Ids are generated by the schema (a UUID per row), not by Better Auth.
    advanced: {
      database: { generateId: false },
      // Rate limits and audit read the caller's address from here; Cloudflare's header cannot be forged.
      ipAddress: { ipAddressHeaders: ["cf-connecting-ip", "x-forwarded-for"] },
      ...(runInBackground ? { backgroundTasks: { handler: runInBackground } } : {}),
    },

    emailAndPassword: {
      enabled: true,
      minPasswordLength: 8,
      // Guests (anonymous) never go through this: they have no e-mail to confirm.
      requireEmailVerification: env.REQUIRE_EMAIL_VERIFICATION,
    },
    emailVerification: {
      sendOnSignUp: env.REQUIRE_EMAIL_VERIFICATION,
      // Trying to sign in before confirming sends a fresh link, so a lost e-mail is not a dead end.
      sendOnSignIn: env.REQUIRE_EMAIL_VERIFICATION,
      // The link signs the visitor in: one click from the inbox to the app.
      autoSignInAfterVerification: true,
      expiresIn: VERIFICATION_TTL_SECONDS,
      // Not awaited by Better Auth, so the response does not reveal whether an address is new.
      async sendVerificationEmail({ user, url }) {
        await mailer.send(
          verificationEmail({ to: user.email, name: user.name, url, expiresInHours: VERIFICATION_TTL_SECONDS / 3600 }),
        );
      },
    },
    socialProviders: googleEnabled
      ? { google: { clientId: env.GOOGLE_CLIENT_ID!, clientSecret: env.GOOGLE_CLIENT_SECRET! } }
      : {},

    plugins: [
      organization({
        creatorRole: "owner",
        // No e-mail provider yet: invitations are shared as a link built from the invitation id,
        // returned by the create-invitation endpoint. This callback intentionally sends nothing.
        async sendInvitationEmail() {},
        // Invitation ids are random UUIDs and e-mail verification is not available yet.
        requireEmailVerificationOnInvitation: false,
        schema: {
          organization: {
            additionalFields: {
              isDemo: { type: "boolean", required: false, input: false },
              demoExpiresAt: { type: "date", required: false, input: false },
            },
          },
        },
      }),
      admin(),
      // Better Auth documents its own endpoints: /api/auth/reference and /api/auth/open-api/generate-schema.
      openAPI(),
      anonymous({
        onLinkAccount: async ({ anonymousUser, newUser }) => {
          await provisioning.adoptDemoWorkspace(anonymousUser.user.id, {
            id: newUser.user.id,
            name: newUser.user.name,
          });
        },
      }),
    ],

    hooks: {
      // Sessions are destroyed by these calls, so who is acting has to be read before they run.
      before: createAuthMiddleware(async (ctx) => {
        if (ctx.path !== "/sign-out" && ctx.path !== "/admin/stop-impersonating") return;
        const current = await getSessionFromCtx(ctx).catch(() => null);
        if (!current) return;

        const { session, user } = current;
        const impersonatedBy = (session as { impersonatedBy?: string | null }).impersonatedBy ?? null;
        const organizationId = (session as { activeOrganizationId?: string | null }).activeOrganizationId ?? null;
        if (ctx.path === "/admin/stop-impersonating") {
          if (!impersonatedBy) return;
          await trace(ctx.request, {
            action: "impersonate_end",
            entityType: "member",
            entityId: user.id,
            organizationId,
            impersonatedById: impersonatedBy,
            user,
          });
        } else {
          await trace(ctx.request, { action: "logout", organizationId, impersonatedById: impersonatedBy, user });
        }
      }),

      after: createAuthMiddleware(async (ctx) => {
        const created = ctx.context.newSession;
        switch (ctx.path) {
          case "/sign-in/email":
          case "/sign-in/anonymous":
          case "/sign-up/email":
          case "/verify-email":
          case "/callback/:id":
            if (created) {
              // A brand-new account gets its session before its first organization exists.
              const organizationId =
                (created.session as { activeOrganizationId?: string | null }).activeOrganizationId ??
                (await provisioning.initialOrganizationId(created.user.id));
              await trace(ctx.request, { action: "login", organizationId, user: created.user });
            }
            return;

          case "/admin/impersonate-user": {
            const impersonatedBy = (created?.session as { impersonatedBy?: string | null } | undefined)?.impersonatedBy;
            if (created && impersonatedBy) {
              await trace(ctx.request, {
                action: "impersonate_start",
                entityType: "member",
                entityId: created.user.id,
                organizationId: (created.session as { activeOrganizationId?: string | null }).activeOrganizationId ?? null,
                impersonatedById: impersonatedBy,
                user: created.user,
              });
            }
            return;
          }

          case "/organization/invite-member":
          case "/organization/remove-member": {
            const result = ctx.context.returned;
            if (!result || result instanceof Error) return;
            const actor = await getSessionFromCtx(ctx).catch(() => null);
            const invited = ctx.path === "/organization/invite-member";
            await trace(ctx.request, {
              action: invited ? "invite_member" : "remove_member",
              entityType: "member",
              entityId: invited ? ((result as { id?: string }).id ?? null) : null,
              details: JSON.stringify(
                invited
                  ? { email: (ctx.body as { email?: string } | undefined)?.email, role: (ctx.body as { role?: string } | undefined)?.role }
                  : { member: (ctx.body as { memberIdOrEmail?: string } | undefined)?.memberIdOrEmail },
              ),
              organizationId:
                (ctx.body as { organizationId?: string } | undefined)?.organizationId ??
                (actor?.session as { activeOrganizationId?: string | null } | undefined)?.activeOrganizationId ??
                null,
              user: actor?.user ?? null,
            });
            return;
          }
        }
      }),
    },

    databaseHooks: {
      user: {
        create: {
          after: async (user) => {
            await provisioning.provisionForNewUser({
              id: user.id,
              name: user.name,
              isAnonymous: Boolean((user as { isAnonymous?: boolean | null }).isAnonymous),
            });
          },
        },
      },
      session: {
        create: {
          before: async (session) => {
            const organizationId = await provisioning.initialOrganizationId(session.userId);
            return { data: { ...session, activeOrganizationId: organizationId ?? undefined } };
          },
        },
      },
    },
  });
}

export type Auth = ReturnType<typeof createAuth>;
