import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { searchKey } from "../db/helpers.js";
import { propertySubtypes, propertyTypeUsages, transactionCategories } from "../db/reference-data/catalog.js";

/**
 * Writes the reference data (cities, property subtypes, usage rules, transaction categories) as a SQL
 * migration, so a database gets it from the same migrations that create its tables (`wrangler d1
 * migrations apply` on D1, the Drizzle migrator on Node). INSERT OR IGNORE makes it safe to re-run.
 *   npm run db:reference-data      (after changing catalog.ts or cities.json; then bump the file's number)
 */
const target = resolve(process.argv[2] ?? "migrations/0002_reference_data.sql");
const quote = (value: string) => `'${value.replace(/'/g, "''")}'`;
const BREAK = "--> statement-breakpoint\n";
const ROWS_PER_STATEMENT = 200;

function insert(table: string, columns: string[], rows: string[][]): string[] {
  const statements: string[] = [];
  for (let index = 0; index < rows.length; index += ROWS_PER_STATEMENT) {
    const values = rows.slice(index, index + ROWS_PER_STATEMENT).map((row) => `(${row.join(", ")})`);
    statements.push(`INSERT OR IGNORE INTO ${table} (${columns.join(", ")}) VALUES\n${values.join(",\n")};\n`);
  }
  return statements;
}

const cities = JSON.parse(await readFile(resolve("src/db/reference-data/cities.json"), "utf8")) as [number, string, string][];

const statements = [
  ...insert(
    "property_subtypes",
    ["property_type", "name"],
    propertySubtypes.map((row) => [quote(row.propertyType), quote(row.name)]),
  ),
  ...insert(
    "property_type_usages",
    ["property_type", "usage_type"],
    propertyTypeUsages.map((row) => [quote(row.propertyType), quote(row.usageType)]),
  ),
  ...insert(
    "transaction_categories",
    ["transaction_type", "name"],
    transactionCategories.map((row) => [quote(row.transactionType), quote(row.name)]),
  ),
  ...insert(
    "cities",
    ["ibge_code", "name", "state", "name_search"],
    cities.map(([code, name, state]) => [String(code), quote(name), quote(state), quote(searchKey(name))]),
  ),
];

await writeFile(target, `-- Reference data. Generated by src/scripts/generate-reference-data.ts: do not edit by hand.\n${statements.join(BREAK)}`);
console.log(`${statements.length} statements written to ${target}`);
