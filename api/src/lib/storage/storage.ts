/** Where the bytes of uploaded files live. The database only keeps the key. */
export interface StorageProvider {
  put(key: string, body: Buffer, options: { contentType: string }): Promise<void>;
  /** `null` when there is no object under the key. */
  get(key: string): Promise<StoredObject | null>;
  /** Idempotent: deleting a key that is not there is not an error. */
  delete(key: string): Promise<void>;
}

export interface StoredObject {
  body: Buffer;
  /** Only drivers that keep it return it; the database also records the type. */
  contentType: string | null;
  sizeBytes: number;
}

/** Keys are generated by the app (`<organization>/<uuid>.<ext>`); anything else is refused. */
const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9._-]*(\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/;

export function assertSafeKey(key: string): void {
  if (!SAFE_KEY.test(key) || key.includes("..") || key.length > 500) {
    throw new Error(`Unsafe storage key: ${JSON.stringify(key)}`);
  }
}
